CREATE TABLE IF NOT EXISTS assets(id TEXT PRIMARY KEY, metadata TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS locations(path TEXT PRIMARY KEY, asset_id TEXT NOT NULL REFERENCES assets(id));
CREATE TABLE IF NOT EXISTS runs(id TEXT PRIMARY KEY, asset_id TEXT NOT NULL REFERENCES assets(id),
  task TEXT NOT NULL, signature TEXT NOT NULL, status TEXT NOT NULL, summary TEXT NOT NULL,
  created REAL NOT NULL);
CREATE INDEX IF NOT EXISTS run_asset_task ON runs(asset_id,task,created);
CREATE TABLE IF NOT EXISTS events(id TEXT PRIMARY KEY, run_id TEXT NOT NULL REFERENCES runs(id),
  asset_id TEXT NOT NULL, type TEXT NOT NULL, part TEXT NOT NULL, t0 REAL NOT NULL,
  t1 REAL NOT NULL, payload TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS event_time ON events(asset_id,t0,t1);
CREATE TABLE IF NOT EXISTS corrections(id INTEGER PRIMARY KEY, asset_id TEXT NOT NULL REFERENCES assets(id),
  field TEXT NOT NULL, value TEXT NOT NULL, reason TEXT NOT NULL, created REAL NOT NULL);
